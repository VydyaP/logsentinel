def page_overview() -> None:
    df = alerts_frame()
    open_df = df[~df["status"].isin(["Resolved", "False positive"])]
    with session_scope() as s:
        open_incidents = s.scalar(
            select(func.count())
            .select_from(Incident)
            .where(Incident.status.not_in(["Resolved", "False positive"]))
        )
        sla = sla_report(s)
    acked = [r for r in sla if r.mtta_minutes is not None]
    mtta = sum(r.mtta_minutes * r.alerts for r in acked) / max(1, sum(r.alerts for r in acked))

    st.title("Overview")
    c = st.columns(5)
    c[0].metric("Events ingested", f"{n_events:,}")
    c[1].metric("Alerts", f"{n_alerts:,}")
    c[2].metric("Open alerts", len(open_df))
    c[3].metric("Open critical/high", int(open_df["severity"].isin(["critical", "high"]).sum()))
    c[4].metric("Open incidents", open_incidents or 0)
    st.caption(f"Mean time to acknowledge across all severities: {mtta:.0f} min")

    timeline = df.assign(hour=df["time"].dt.floor("1h"))
    timeline = timeline.groupby(["hour", "severity"]).size().reset_index(name="alerts")
    chart = (
        alt.Chart(timeline, title="Alerts over time (by hour of first event, UTC)")
        .mark_bar(stroke="white", strokeWidth=1, cornerRadiusTopLeft=2, cornerRadiusTopRight=2)
        .encode(
            x=alt.X("hour:T", title=None),
            y=alt.Y("alerts:Q", title="Alerts", stack=True, axis=alt.Axis(tickMinStep=1)),
            color=alt.Color(
                "severity:N", scale=severity_scale(), title="Severity", sort=SEVERITIES
            ),
            order=alt.Order("severity_rank:Q"),
            tooltip=[alt.Tooltip("hour:T", format="%d %b %H:00"), "severity:N", "alerts:Q"],
        )
        .transform_calculate(
            severity_rank="indexof(['low','medium','high','critical'], datum.severity)"
        )
        .properties(height=260)
    )
    st.altair_chart(chart, use_container_width=True)

    left, right = st.columns(2)
    left.altair_chart(hbar(df, "source", "Top offending sources"), use_container_width=True)
    tech = df.assign(
        technique=df["technique"].fillna("n/a") + " " + df["technique_name"].fillna("Anomaly")
    )
    right.altair_chart(
        hbar(tech, "technique", "Alerts by MITRE ATT&CK technique"), use_container_width=True
    )

    sev = df.groupby("severity").size().reindex(SEVERITIES, fill_value=0).reset_index(name="alerts")
    sev_chart = (
        alt.Chart(sev, title="Alerts by severity")
        .mark_bar(cornerRadiusEnd=4, size=18)
        .encode(
            x=alt.X("alerts:Q", title="Alerts", axis=alt.Axis(tickMinStep=1)),
            y=alt.Y("severity:N", sort=SEVERITIES, title=None),
            color=alt.Color("severity:N", scale=severity_scale(), legend=None),
            tooltip=["severity:N", "alerts:Q"],
        )
    )
    st.altair_chart(sev_chart, use_container_width=True)


def alert_detail(alert_id: int) -> None:
    with session_scope() as s:
        alert = s.get(Alert, alert_id)
        if alert is None:
            st.warning("Alert not found.")
            return
        st.subheader(
            f"{SEVERITY_ICON[alert.severity]} #{alert.id} {alert.rule_id}: {alert.rule_name}"
        )
        st.write(alert.description)
        a, b, c, d = st.columns(4)
        a.metric("Severity", alert.severity.title())
        b.metric("Status", alert.status)
        c.metric("Source", alert.entity)
        d.metric("Events", alert.event_count)
        mitre = (
            f"[{alert.mitre_technique}](https://attack.mitre.org/techniques/"
            f"{alert.mitre_technique.replace('.', '/')}/) {alert.mitre_name} ({alert.mitre_tactic})"
            if alert.mitre_technique
            else "n/a (behavioural anomaly)"
        )
        st.markdown(
            f"**MITRE ATT&CK:** {mitre}  \n"
            f"**First / last event:** {alert.first_event_at:%Y-%m-%d %H:%M:%S} / "
            f"{alert.last_event_at:%H:%M:%S} UTC  \n"
            f"**Incident:** INC-{alert.incident_id or 0:05d} · "
            f"**Assignee:** {alert.assignee or 'unassigned'}"
            + (f"  \n**Anomaly score:** {alert.score:.3f}" if alert.score is not None else "")
        )
        if alert.details.get("unusual_features"):
            st.caption("Stands out on: " + ", ".join(alert.details["unusual_features"]))

        st.markdown("**Raw log lines that triggered this alert**")
        lines = [e.raw for e in alert.events]
        st.code("\n".join(lines[:200]) or "(no linked events)", language="log")
        if alert.event_count > len(lines):
            st.caption(f"Showing the first {len(lines)} of {alert.event_count} events.")

        st.markdown("**Notes and history**")
        for note in reversed(alert.notes):
            st.markdown(f"- `{note.created_at:%Y-%m-%d %H:%M}` **{note.author}**: {note.body}")
        if not alert.notes:
            st.caption("No notes yet.")
        incident_size = len(alert.incident.alerts) if alert.incident else 1
        current_status = alert.status
        current_assignee = alert.assignee or ""

    if settings.read_only:
        st.info("Read-only demo: triage actions are disabled.")
        return
    with st.form(f"triage-{alert_id}"):
        st.markdown("**Triage**")
        col1, col2 = st.columns(2)
        status = col1.radio(
            "Status", STATUSES, index=STATUSES.index(current_status), horizontal=True
        )
        assignee = col2.text_input("Assignee", value=current_assignee or analyst)
        note = st.text_area("Add a note", placeholder="What did you check? What did you do?")
        whole_incident = st.checkbox(
            f"Apply status to all {incident_size} alert(s) in this incident", value=False
        )
        if st.form_submit_button("Save", type="primary"):
            with session_scope() as s:
                alert = s.get(Alert, alert_id)
                assert alert is not None
                targets = alert.incident.alerts if whole_incident and alert.incident else [alert]
                for target in targets:
                    update_alert(
                        s,
                        target,
                        status=status,
                        assignee=assignee or None,
                        note=note if target.id == alert_id else None,
                        author=analyst,
                    )
            st.success("Saved.")
            st.rerun()


def page_alerts() -> None:
    st.title("Alerts")
    df = alerts_frame()
    f1, f2, f3, f4 = st.columns(4)
    status = f1.multiselect("Status", STATUSES, default=["New", "Investigating"])
    severity = f2.multiselect("Severity", SEVERITIES, default=[])
    rule = f3.multiselect("Rule", sorted(df["rule"].unique()), default=[])
    search = f4.text_input("Source contains")
    view = df
    if status:
        view = view[view["status"].isin(status)]
    if severity:
        view = view[view["severity"].isin(severity)]
    if rule:
        view = view[view["rule"].isin(rule)]
    if search:
        view = view[view["source"].str.contains(search, case=False, regex=False)]
    view = view.assign(severity=view["severity"].map(lambda s: f"{SEVERITY_ICON[s]} {s}"))
    st.caption(f"{len(view)} of {len(df)} alerts · click a row to open it")
    event = st.dataframe(
        view[
            [
                "id",
                "time",
                "severity",
                "rule",
                "rule_name",
                "source",
                "status",
                "assignee",
                "events",
                "incident",
            ]
        ],
        hide_index=True,
        use_container_width=True,
        on_select="rerun",
        selection_mode="single-row",
        column_config={
            "time": st.column_config.DatetimeColumn("First event (UTC)", format="YYYY-MM-DD HH:mm")
        },
    )
    rows = event.selection.rows if event and event.selection else []
    if rows:
        st.session_state["alert_id"] = int(view.iloc[rows[0]]["id"])
    elif "alert_id" not in st.session_state and st.query_params.get("alert", "").isdigit():
        st.session_state["alert_id"] = int(st.query_params["alert"])
    if "alert_id" in st.session_state:
        st.divider()
        alert_detail(st.session_state["alert_id"])


def page_incidents() -> None:
    from logsentinel.report import generate_report

    st.title("Incidents")
    st.caption("Alerts from the same source within the grouping window form one incident.")
    with session_scope() as s:
        incidents = s.scalars(select(Incident).order_by(Incident.last_seen.desc())).all()
        rows = [
            {
                "id": i.id,
                "incident": f"INC-{i.id:05d}",
                "severity": f"{SEVERITY_ICON[i.severity]} {i.severity}",
                "status": i.status,
                "title": i.title,
                "alerts": len(i.alerts),
                "first seen": i.first_seen,
                "last seen": i.last_seen,
                "ticket": i.external_ref,
            }
            for i in incidents
        ]
    df = pd.DataFrame(rows)
    event = st.dataframe(
        df.drop(columns=["id"]),
        hide_index=True,
        use_container_width=True,
        on_select="rerun",
        selection_mode="single-row",
    )
    selected = event.selection.rows if event and event.selection else []
    if not selected:
        st.info("Select an incident to see its alerts and download the report.")
        return
    incident_id = int(df.iloc[selected[0]]["id"])
    with session_scope() as s:
        md_text, pdf_bytes, _ = generate_report(s, incident_id)
    c1, c2 = st.columns(2)
    c1.download_button(
        "Download report (PDF)",
        pdf_bytes,
        f"INC-{incident_id:05d}.pdf",
        mime="application/pdf",
        type="primary",
    )
    c2.download_button(
        "Download report (Markdown)", md_text, f"INC-{incident_id:05d}.md", mime="text/markdown"
    )
    with st.expander("Report preview", expanded=True):
        st.markdown(md_text)


def page_sla() -> None:
    st.title("SLA")
    st.caption(
        "Time to acknowledge = first status/assignee change; time to resolve = closed as "
        "Resolved or False positive. Open alerts past their target count as breaches."
    )
    with session_scope() as s:
        rows = sla_report(s)
    df = pd.DataFrame([vars(r) for r in rows])
    df["severity"] = df["severity"].map(lambda v: f"{SEVERITY_ICON[v]} {v}")
    df = df.rename(
        columns={
            "alerts": "Alerts",
            "open": "Open",
            "mtta_minutes": "MTTA (min)",
            "mttr_minutes": "MTTR (min)",
            "ack_target_minutes": "Ack target (min)",
            "resolve_target_minutes": "Resolve target (min)",
            "ack_breaches": "Ack breaches",
            "resolve_breaches": "Resolve breaches",
            "severity": "Severity",
        }
    )
    st.dataframe(df, hide_index=True, use_container_width=True)

    long = pd.DataFrame([vars(r) for r in rows])
    long = long.melt(
        id_vars="severity",
        value_vars=["ack_breaches", "resolve_breaches"],
        var_name="kind",
        value_name="breaches",
    )
    long["kind"] = long["kind"].map({"ack_breaches": "Acknowledge", "resolve_breaches": "Resolve"})
    chart = (
        alt.Chart(long, title="SLA breaches by severity")
        .mark_bar(cornerRadiusEnd=4, size=12)
        .encode(
            x=alt.X("breaches:Q", title="Breaches", axis=alt.Axis(tickMinStep=1)),
            y=alt.Y("severity:N", sort=SEVERITIES, title=None),
            yOffset=alt.YOffset("kind:N", sort=["Acknowledge", "Resolve"]),
            color=alt.Color("kind:N", scale=alt.Scale(range=["#2a78d6", "#eb6834"]), title="SLA"),
            tooltip=["severity:N", "kind:N", "breaches:Q"],
        )
    )
    st.altair_chart(chart, use_container_width=True)
    st.markdown("**Targets**")

    def human(td: timedelta) -> str:
        minutes = int(td.total_seconds() // 60)
        return f"{minutes} min" if minutes < 60 else f"{minutes // 60} h"

    targets = [
        {"Severity": k, "Acknowledge within": human(v[0]), "Resolve within": human(v[1])}
        for k, v in SLA_TARGETS.items()
    ]
    st.dataframe(pd.DataFrame(targets), hide_index=True)


def page_upload() -> None:
    from logsentinel.ingest import ingest_lines
    from logsentinel.pipeline import run_detection

    st.title("Upload logs")
    st.write(
        "Upload a Linux SSH auth log (`auth.log` / `secure`) or an Nginx/Apache access log "
        "(combined format). Events are stored and detection runs straight away. Max 20 MB."
    )
    if settings.read_only:
        st.info("Read-only demo: uploads are disabled.")
        return
    file = st.file_uploader("Log file", type=["log", "txt"], accept_multiple_files=False)
    log_type = st.radio("Format", ["auto", "ssh", "web"], horizontal=True)
    year = st.number_input(
        "Year (only for classic syslog lines without a year)", 2000, 2100, datetime.now(UTC).year
    )
    if file and st.button("Ingest and detect", type="primary"):
        if file.size > 20 * 1024 * 1024:
            st.error("File larger than 20 MB.")
            return
        lines = file.getvalue().decode("utf-8", errors="replace").splitlines()
        with st.spinner("Parsing and detecting..."), session_scope() as s:
            stats = ingest_lines(s, lines, log_type, source_file=file.name, year=int(year))
            if stats.log_type is None:
                st.error("Could not recognise the log format.")
                return
            run = run_detection(s)
        st.success(
            f"{stats.log_type} log: {stats.inserted:,} new events "
            f"({stats.duplicates:,} already stored, {stats.skipped_lines:,} lines skipped). "
            f"{len(run.new_alerts)} new alert(s)."
        )
    st.caption(
        "Tip: try the real public sample `data/real/OpenSSH_2k.log` (year 2015) from the repo."
    )


def page_rules() -> None:
    st.title("Detection rules")
    st.write(
        "Rules live in YAML files under `rules/`. Adding a detection means adding YAML, "
        "not code. Each rule maps to a MITRE ATT&CK technique and has a runbook."
    )
    rules = load_rules(settings.rules_dir)
    table = pd.DataFrame(
        [
            {
                "ID": r.id,
                "Name": r.name,
                "Severity": f"{SEVERITY_ICON[r.severity]} {r.severity}",
                "Type": r.type,
                "Threshold": r.threshold,
                "Window": r.window,
                "MITRE": f"{r.mitre.technique_id} {r.mitre.technique_name}",
                "Tactic": r.mitre.tactic,
            }
            for r in rules
        ]
    )
    st.dataframe(table, hide_index=True, use_container_width=True)
    st.caption("Plus ANOM-001: Isolation Forest anomaly detection on per-IP hourly behaviour.")
    for r in rules:
        with st.expander(f"{r.id} {r.name}: runbook"):
            path = ROOT / (r.runbook or "")
            st.markdown(path.read_text() if r.runbook and path.exists() else "No runbook.")


