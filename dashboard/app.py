def severity_scale() -> alt.Scale:
    return alt.Scale(domain=SEVERITIES, range=SEVERITY_COLORS)


def hbar(df: pd.DataFrame, field: str, title: str, color: str = BAR_COLOR) -> alt.Chart:
    """Horizontal bar chart of alert counts per ``field`` (single series, one color)."""
    data = df.groupby(field).size().reset_index(name="alerts").nlargest(10, "alerts")
    return (
        alt.Chart(data, title=title)
        .mark_bar(color=color, cornerRadiusEnd=4, size=14)
        .encode(
            x=alt.X("alerts:Q", title="Alerts", axis=alt.Axis(tickMinStep=1, grid=True)),
            y=alt.Y(f"{field}:N", sort="-x", title=None, axis=alt.Axis(labelLimit=320)),
            tooltip=[alt.Tooltip(f"{field}:N"), alt.Tooltip("alerts:Q")],
        )
        .properties(height=alt.Step(24))
    )


