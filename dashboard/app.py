@st.cache_resource
def _bootstrap() -> bool:
    """Make sure tables exist when running on a local SQLite file."""
    if get_engine().dialect.name == "sqlite":
        init_db()
    return True


def alerts_frame() -> pd.DataFrame:
    with session_scope() as s:
        rows = s.execute(
            select(
                Alert.id,
                Alert.first_event_at,
                Alert.severity,
                Alert.rule_id,
                Alert.rule_name,
                Alert.entity,
                Alert.status,
                Alert.assignee,
                Alert.mitre_technique,
                Alert.mitre_name,
                Alert.event_count,
                Alert.incident_id,
                Alert.description,
            ).order_by(Alert.first_event_at.desc())
        ).all()
    df = pd.DataFrame(
        rows,
        columns=[
            "id",
            "time",
            "severity",
            "rule",
            "rule_name",
            "source",
            "status",
            "assignee",
            "technique",
            "technique_name",
            "events",
            "incident",
            "description",
        ],
    )
    df["time"] = pd.to_datetime(df["time"], utc=True)
    return df


def counts() -> tuple[int, int]:
    with session_scope() as s:
        return (
            s.scalar(select(func.count()).select_from(Event)) or 0,
            s.scalar(select(func.count()).select_from(Alert)) or 0,
        )


